const assert = require('node:assert/strict');
const fs = require('node:fs');
const read = (p) => fs.readFileSync(p, 'utf8');
const bridge = read('src/notifications/exactAlarmPermission.ts');
const persistence = read('src/notifications/persistence.ts');
const root = read('app/_layout.tsx');
const screen = read('app/notifications.tsx');
const native = read('modules/weekflow-exact-alarms/android/src/main/java/expo/modules/weekflowalarms/WeekFlowExactAlarmsModule.kt');
const app = JSON.parse(read('app.json'));

assert.match(root, /onboardingRequired !== false\) return/, 'onboarding is not interrupted');
assert.match(root, /offerExactAlarmAccessIfNeeded\(\)/, 'first eligible app entry offers special access');
assert.match(bridge, /const status = await getExactAlarmPermissionStatus\(\)/, 'permission must be queried from OS');
assert.match(bridge, /if \(status !== 'blocked'/, 'only denied special access is offered');
assert.match(bridge, /!loadNotificationPreferences\(\)\.enabled/, 'disabled notifications do not cause prompts');
assert.match(bridge, /hasSeenExactAlarmPermissionOffer\(\)/, 'prompt is offered once, not at every launch');
assert.match(persistence, /notification-exact-alarm-offer-v1/, 'local state key isolates one-time explanation');
assert.match(persistence, /sqliteStateStore\.write\(EXACT_ALARM_OFFER_SEEN_KEY, true\)/, 'offer is persisted with existing key-value store');
assert.match(bridge, /'Más tarde'/, 'no forced permission request');
assert.match(bridge, /'Abrir permisos', onPress:/, 'system settings only opens after explicit tap');
assert.match(bridge, /openExactAlarmPermissionSettings\(\)/, 'existing official intent is used');
assert.match(native, /Settings\.ACTION_REQUEST_SCHEDULE_EXACT_ALARM/, 'native platform special permission intent');
assert.match(native, /canScheduleExactAlarms\(\)/, 'native access check remains');
assert.match(screen, /style=\{styles\.permissionCard\}/, 'special access appears at top of notification screen');
assert.match(screen, /Activar alarmas exactas/, 'clear activation action');
assert.match(screen, /onPress=\{\(\) => void openExactAlarmSettings\(\)\}/, 'activation button actionable');
assert.ok(screen.indexOf('Activar alarmas exactas') < screen.indexOf('QUÉ QUIERES RECIBIR'), 'permission action precedes secondary settings');
assert.match(screen, /if \(saved\.enabled\) void offerExactAlarmAccessIfNeeded\(\)/, 'enabling reminders can offer permission');
assert.match(screen, /AppState\.addEventListener\('change'/, 'status refreshed on return from system settings');
assert.match(screen, /scheduleWeekFlowLongIdleTest\(\)/, 'long idle diagnostic still available');
assert.match(screen, /scheduleWeekFlowNotificationTest\(\)/, 'five-second diagnostic still available');
assert.ok(app.expo.android.permissions.includes('android.permission.SCHEDULE_EXACT_ALARM'));
assert.equal(app.expo.android.package, 'com.weekflow.app');
console.log('WeekFlow proactive exact alarm permission request and settings structure passed.');
