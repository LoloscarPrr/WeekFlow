const assert = require('node:assert/strict');
const fs = require('node:fs');
const read = (path) => fs.readFileSync(path, 'utf8');
const config = JSON.parse(read('app.json'));
const moduleConfig = JSON.parse(read('modules/weekflow-exact-alarms/expo-module.config.json'));
const native = read('modules/weekflow-exact-alarms/android/src/main/java/expo/modules/weekflowalarms/WeekFlowExactAlarmsModule.kt');
const bridge = read('src/notifications/exactAlarmPermission.ts');
const service = read('src/services/notifications.ts');
const screen = read('app/notifications.tsx');
const workflow = read('.github/workflows/build-weekflow-native.yml');

assert.ok(moduleConfig.platforms.includes('android'), 'Android-only local native module');
assert.ok(moduleConfig.android.modules.includes('expo.modules.weekflowalarms.WeekFlowExactAlarmsModule'), 'module registered for Expo autolinking');
assert.ok(native.includes('manager.canScheduleExactAlarms()'), 'actual AlarmManager privilege, not POST_NOTIFICATIONS');
assert.ok(native.includes('Settings.ACTION_REQUEST_SCHEDULE_EXACT_ALARM'), 'special settings intent');
assert.ok(native.includes('Settings.ACTION_APPLICATION_DETAILS_SETTINGS'), 'fallback for Xiaomi settings');
assert.ok(native.includes('Build.VERSION.SDK_INT < Build.VERSION_CODES.S'), 'older Android needs no special access');
assert.ok(!native.includes('USE_EXACT_ALARM'), 'do not use restricted automatic privilege');
assert.ok(bridge.includes("return 'unavailable'"), 'missing native module cannot be misreported as a denial');
assert.ok(bridge.includes("return await native.canScheduleExactAlarmsAsync() ? 'allowed' : 'blocked'"), 'status derived from the real OS API');
assert.ok(bridge.includes("openExactAlarmPermissionSettings"), 'settings action is not automatic');
assert.ok(service.includes('exactAlarmPermission: ExactAlarmPermissionStatus'), 'separate native status included in diagnostics');
assert.ok(service.includes('getExactAlarmPermissionStatus()'), 'diagnostics reads the current Android state');
assert.ok(screen.includes("diagnostics?.exactAlarmPermission === 'blocked'"), 'explicit blocked warning');
assert.ok(screen.includes("diagnostics?.exactAlarmPermission === 'unavailable'"), 'missing/native-error state is honest');
assert.ok(screen.includes('Revisar alarmas exactas'), 'user can open the correct settings screen');
assert.ok(screen.includes("AppState.addEventListener('change'"), 'diagnostic refreshes on return');
assert.ok(screen.includes('scheduleWeekFlowLongIdleTest()'), 'DATE test remains');
assert.ok(screen.includes('scheduleWeekFlowNotificationTest()'), 'TIME_INTERVAL test remains');
assert.ok(screen.includes('Linking.openSettings()'), 'generic fallback remains');
assert.ok(config.expo.android.permissions.includes('android.permission.SCHEDULE_EXACT_ALARM'), 'manifest explicitly requests privilege');
assert.ok(!config.expo.android.permissions.includes('android.permission.USE_EXACT_ALARM'), 'do not request restricted permission');
assert.equal(config.expo.android.package,'com.weekflow.app');
assert.ok(workflow.includes('"modules/**"'), 'build runs when only native module changes');
console.log('WeekFlow Android exact alarm status and settings guards passed.');
