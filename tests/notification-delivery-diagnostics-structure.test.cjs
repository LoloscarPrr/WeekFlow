const fs = require('node:fs');
const assert = require('node:assert/strict');
const service = fs.readFileSync('src/services/notifications.ts','utf8');
const screen = fs.readFileSync('app/notifications.tsx','utf8');
const prefs = fs.readFileSync('src/notifications/persistence.ts','utf8');
const config = JSON.parse(fs.readFileSync('app.json','utf8'));
const testFn = service.slice(service.indexOf('export async function scheduleWeekFlowNotificationTest('), service.indexOf('async function performLivePlanReminderSync('));
assert.ok(testFn.includes('await initializeNotifications()'), 'diagnostic tests require OS permission');
assert.ok(testFn.includes('SchedulableTriggerInputTypes.TIME_INTERVAL'), 'test is independent of agenda dates');
assert.ok(testFn.includes('seconds: 5'), 'five-second test');
assert.ok(testFn.includes("kind: 'diagnostic-test'"), 'diagnostic kind is not reconciled as a planned reminder');
assert.ok(!testFn.includes('weekflowReminderId:'), 'diagnostic test never looks like live plan');
assert.ok(!testFn.includes('cancelAllWeekFlowReminders'), 'test does not cancel user reminders');
assert.ok(service.includes('getNotificationChannelAsync(WEEKFLOW_NOTIFICATION_CHANNEL)'), 'channel is inspected');
assert.ok(service.includes('scheduledManagedCount: requests.filter'), 'total registered count is read');
assert.ok(screen.includes('getNotificationDeliveryDiagnostics()'), 'UI shows Android status');
assert.ok(screen.includes('Recordatorios pendientes en Android:'), 'UI shows existing pending count');
assert.ok(screen.includes('scheduleWeekFlowNotificationTest()'), 'test is explicitly activated');
assert.ok(screen.includes('Linking.openSettings()'), 'system settings are accessible');
assert.ok(screen.includes('Alarmas y recordatorios'), 'explain special alarm permission');
assert.ok(screen.includes('Sin restricciones'), 'explain Xiaomi battery restrictions');
assert.ok(!screen.includes('No hay avisos futuros que programar ahora'), '0 newly scheduled != 0 registered');
assert.ok(service.includes('reconcileScheduledReminders(scheduled, reminders, allReminders)'), 'existing reconciliation remains');
assert.ok(prefs.includes('FRESH_NOTIFICATION_PREFERENCES'), 'opt-in defaults preserved');
assert.ok(config.expo.android.permissions.includes('android.permission.SCHEDULE_EXACT_ALARM'), 'exact alarm access can be enabled');
assert.equal(config.expo.android.package,'com.weekflow.app');
console.log('WeekFlow notification delivery diagnostics structure regressions passed.');
