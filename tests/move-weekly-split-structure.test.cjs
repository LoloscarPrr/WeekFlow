const fs = require('fs');
const read = p => fs.readFileSync(p,'utf8');
const ok = (v,m) => { if (!v) throw Error(m); };
const planner=read('src/brain/weeklyPlanner.ts');
const split=read('src/move/weeklySplit.ts');
const controller=read('src/move/useMoveController.ts');
const persistence=read('src/state/persistence.ts');
const ui=read('src/move/MovePlan.tsx');
const confirm=read('src/brain/weeklyPlanPersistence.ts');
ok(planner.includes('moveWeeklySplit(prefs, targetMove)'), 'planificador usa split por frecuencia');
ok(planner.includes('targetMuscles: sessionMuscles'), 'cada sesión obtiene músculos explícitos');
ok(planner.includes('routineForDuration(durationMin, sessionPreferences'), 'rutina usa los músculos de ese día');
ok(split.includes('intersect(selected, PUSH)'), 'no inventa músculos ajenos al objetivo');
ok(controller.includes('prepareWeeklySession(slot: WeeklyMoveSlot)'), 'sesión se puede preparar desde plan confirmado');
ok(controller.includes('loadConfirmedWeeklyPlan()'), 'no acepta sesiones no confirmadas');
ok(controller.includes('effectivePreferences.targetMuscles'), 'motor usa objetivos de sesión real');
ok(controller.includes('targetMuscles: [...effectivePreferences.targetMuscles]'), 'sesión persiste su propio objetivo');
ok(controller.includes('targetMuscles: activeSession.targetMuscles'), 'historial captura músculos entrenados');
ok(controller.includes('activeSession?.targetMuscles ?? preparedWeekly?.targetMuscles'), 'al retomar sesión se usan músculos guardados');
ok(controller.includes('setPreparedWeekly(null)'), 'no filtra selección temporal a futuras sesiones');
ok(persistence.includes('sanitizeTargetMuscles(parsed.targetMuscles)'), 'sesión antigua y nueva conviven');
ok(ui.includes('prepareWeeklySession(plannedMove)'), 'botón prepara músculos, no solo minutos');
ok(ui.includes('No modifica tu perfil general'), 'mensaje explica perfil temporal');
ok(confirm.includes('s.targetMuscles ?? []'), 'confirmación detecta cambios al split');
console.log('Weekly Move guided session structural tests passed.');
