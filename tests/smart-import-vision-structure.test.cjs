const fs=require('fs');
function ok(v,m){if(!v)throw new Error(m);}
const screen=fs.readFileSync('src/components/ScheduleImportCard.tsx','utf8');
const gateway=fs.readFileSync('src/import/visionGateway.ts','utf8');
const contract=fs.readFileSync('src/import/visionContract.ts','utf8');
const server=fs.readFileSync('supabase/functions/vision-schedule/index.ts','utf8');
const config=fs.readFileSync('supabase/config.toml','utf8');
const workflow=fs.readFileSync('.github/workflows/build-weekflow-native.yml','utf8');
const privacy=fs.readFileSync('PRIVACY_POLICY.md','utf8');
ok(gateway.includes('EXPO_PUBLIC_WEEKFLOW_VISION_URL')&&gateway.includes('visionOnlineConfigured'),'no endpoint => no IA UI');
ok(screen.includes("visionOnlineConfigured && pending.source !== 'excel'"),'cloud only for images with endpoint');
ok(screen.includes("onPress={requestVisionConsent}")&&screen.includes('Alert.alert('),'explicit consent needed');
ok(screen.includes("text: 'Cancelar'")&&screen.includes("text: 'Enviar esta foto'"),'consent action per photo');
ok(screen.includes('readVisionSchedule(pending.uri, cleanName)'),'cloud only invoked after user decision');
ok(screen.includes('recognizeText(pending.uri)'),'offline OCR remains available');
ok(screen.includes('confirmReviewedImport({')&&screen.includes('undoReviewedImport(savedReceipt)'),'only canonical commit/undo persists');
ok(gateway.includes('getAuth().currentUser')&&gateway.includes('getIdToken()'),'client uses Firebase session');
ok(gateway.includes("method: 'POST'")&&gateway.includes("Authorization: 'Bearer '"),'token-authenticated POST');
ok(gateway.includes('https:')&&gateway.includes('AbortController'),'encrypted endpoint and timeout');
ok(!gateway.includes('OPENAI_API_KEY')&&!screen.includes('OPENAI_API_KEY'),'no AI API secret in APK');
ok(contract.includes('rowMatchCount === 1')&&contract.includes('No hay una única fila'),'strict identity');
ok(contract.includes('breakMinutes === null')&&contract.includes('issue'),'uncertainty is not silently saved');
ok(server.includes('jwtVerify(token, jwks')&&server.includes("algorithms: ['RS256']"),'server verifies Google Firebase signed tokens');
ok(server.includes('email_verified === true'),'cloud requires verified Firebase identity');
ok(server.includes("ENABLE_WEEKFLOW_VISION")&&server.includes('MAX_BYTES'),'server opt-in and payload limit');
ok(server.includes('store: false')&&server.includes("type: 'input_image'"),'vision model sees image without stored response');
ok(server.includes('json_schema')&&server.includes('additionalProperties: false'),'strict model shape');
ok(config.includes('verify_jwt = false')&&server.includes('verifyUser(req)'),'Firebase JWT verified by handler');
ok(workflow.includes('vars.WEEKFLOW_VISION_URL'),'build exposes only optional public endpoint');
ok(privacy.includes('únicamente si se habilita')&&privacy.includes('nombres y turnos de compañeros'),'privacy of workplace images disclosed');
console.log('Smart Import vision gateway security and UI structure tests passed.');
